"""Surface contracts of camunda-mcp: tool use, links, data locations and roles.

The business tasks first: each is the ordered tool calls a proven workflow uses
(deploy a process, run and monitor an instance, work the human task queue,
evaluate a decision, recover an incident). Then one single-step contract and
link per engine operation, so every served tool is called by a contract and
named by a link. Served as ``ontology://camunda-mcp/contracts.ttl``.
"""

